/**
 * routes/deepinfra.js — the one place a paid cloud generation actually happens (MPI-851).
 *
 * The renderer cannot make this call itself, and must not: the API key lives in the main
 * process and there is no channel that hands it out (set / has / clear only, by design).
 * So the renderer asks for a generation by MODEL ID and this route resolves everything
 * else — which endpoint, which key, which body. Taking the endpoint id from the client
 * would let any renderer path spend the user's money at any model on DeepInfra's
 * catalogue; taking the model id means the ModelDef is the whitelist.
 *
 * THE NATIVE ROUTE, NOT THE OPENAI-COMPATIBLE ONE. `POST /v1/inference/<model>` returns
 * `inference_status.cost` — the true figure for this call. The OpenAI-shaped routes
 * return `created` and `data` and nothing else, so dispatching there would lose the cost
 * entirely and leave the spend readout summing estimates.
 *
 * BYTES, NOT A LINK. DeepInfra hands images back as base64 (and video as a URL), while
 * `save-generation` wants something it can stream and derives the file extension from a
 * `?filename=`. So the bytes land in a scratch file here and the response points at
 * `GET /deepinfra/output/:id`, which is a real http URL with a real extension — the save
 * path is then completely unchanged. It matters that the extension is right rather than
 * assumed: the same family returns JPEG on one tier and PNG on another.
 *
 * WHAT NEVER LEAVES THIS FILE: the key, and the upstream response body. A DeepInfra
 * error body can carry account detail, and `routes/secretRedaction.js` is five regexes
 * for key-shaped strings — it cannot scrub a name or an address. So failures are
 * answered as a CODE plus a message this file wrote, and nothing upstream reaches
 * `logger.*`, which is exfiltratable by design.
 *
 *   POST /deepinfra/generate  { modelId, operation, prompt, seed, width, height,
 *                               ratioLabel, qualityTier, duration, imagePaths, batch,
 *                               estimateUsd }
 *     -> { ok:true, viewUrls:[…], cost:{ usd, model, at }, seed }
 *        The size arrives in every currency the caller knows and `buildSizeFields`
 *        picks the one THIS endpoint takes — pixels, a 'WIDTHxHEIGHT' string, a bare
 *        ratio label, or a resolution tier plus a ratio plus a duration. `batch` is the
 *        provider's own native count where it has one (`num_images`, or Veo's
 *        `sample_count`): N outputs, ONE call, ONE bill.
 *     -> { ok:false, error:{ code, message } }   NO_KEY | NO_PROFILE | NO_CREDIT |
 *                                                CONTENT_FILTERED | PROVIDER_ERROR |
 *                                                LOW_BALANCE | OVER_LIMIT (refused
 *                                                before dispatch; message carries the figures)
 *   GET  /deepinfra/output/:id  -> the generated bytes; kept 24 h, then swept.
 *   GET  /deepinfra/account     -> this month's spend and both stops (MPI-855), numbers only.
 */

