/**
 * deepinfraPricing.js — what a paid cloud generation will cost, BEFORE it runs (MPI-850).
 *
 * Three surfaces need this one number: the prompt box's live tag (MPI-852), the agent's
 * confirm card (MPI-854) and the Model Library tile (MPI-853). Three copies of a pricing
 * formula is three places to drift, so the arithmetic lives here once and every consumer
 * calls `estimateCost()`.
 *
 * ── The two formulas, both MEASURED against real billing, not published ─────────────────
 * Everything below was decomposed from `inference_status.cost` on real calls costing $0.68
 * in total, on 2026-09-20. `docs/proprietary-models-research/01d-deepinfra-image-video.md`
 * § 2b/2c/3 carries the raw figures. DO NOT re-derive them — it costs money, and it has
 * already been done to the cent.
 *
 *   Open image models:  cost = (cents_per_image_unit / 100) x (w x h)/1048576
 *                              x (steps / default_iterations)
 *     Four FLUX-1-schnell probes: $0.0005 per megapixel per step, flat at every size.
 *     Linear in area, linear in steps, no tiering, no rounding.
 *
 *   Video:              tokens = floor(w x h x frames / 1024),  frames = 24 x duration + 1
 *     Exact against an ffprobe of a real clip: 864x496 x 97 / 1024 = 40,594.5 -> 40,594
 *     billed. It is FRAMES, not seconds — `fps x duration` misses by 1%. And "480p 16:9"
 *     is really 864x496, so price from true pixels and never from the label.
 *
 * ── Where the numbers come from ─────────────────────────────────────────────────────────
 * The per-model RATES come from `dev_configs/deepinfra-prices.json`, a snapshot of
 * DeepInfra's own keyless catalogue regenerated by `scripts/sync-deepinfra-prices.mjs`.
 * That keeps a price change a reviewable diff rather than a silent drift, and carries a
 * `checkedOn` date — a stale price quoted at a user is worse than no price at all.
 *
 * The constants in THIS file are only the part that feed cannot express: the Gemini
 * family's per-resolution token counts and their unpublished input/text rates, Seedance's
 * billing band, Veo's fixed clip length, and the video pixel dimensions behind a
 * resolution label.
 *
 * ── Refusing is a feature ───────────────────────────────────────────────────────────────
 * An unknown model id, a `time`-priced model (GPU-seconds, unknowable before the run) or a
 * missing duration returns `null`, never a number. A confidently wrong price costs the user
 * real money; no price costs them a sentence of UI copy.
 */

import SNAPSHOT from '../../../dev_configs/deepinfra-prices.json' with { type: 'json' };

/** When the rates in the snapshot were last read off DeepInfra. */
export const PRICES_CHECKED_ON = SNAPSHOT.checkedOn;

/**
 * True pixel dimensions behind a resolution label (01d § 2c). Only 480p is MEASURED —
 * a real clip came back 864x496, not the 854x480 the label suggests. 720p and 1080p are
 * assumed and should be confirmed from the first real clip at each.
 */
export const VIDEO_PIXELS = {
    '480p': { width: 864, height: 496 },
    '720p': { width: 1280, height: 720 },
    '1080p': { width: 1920, height: 1088 },
};

/**
 * The Gemini image family. DeepInfra's structured rate is the OUTPUT IMAGE rate only; the
 * token counts, the input-image rate and the text rate are published nowhere and were
 * inferred by exact decomposition of three real edits (01d § 3).
 *
 * `outputTokens` is keyed by resolution bucket. Nothing above ~1 MP was reachable on the
 * native route, so lite and NB2 carry one bucket and an unknown bucket falls back to it.
 * A reference image bills a FLAT token count whatever its size — a 3 MP PNG billed the
 * same 1120 as a small one.
 */
const GEMINI_IMAGE = {
    'google/nano-banana-2-lite': {
        outputTokens: { '1k': 1120 }, outputRatePerM: 30,
        textTokens: 0, textRatePerM: 0,          // no text output seen on lite
        refTokens: 1120, inputRatePerM: 0.25,
    },
    'google/nano-banana-2': {
        outputTokens: { '1k': 1120 }, outputRatePerM: 60,
        textTokens: 32, textRatePerM: 3,
        refTokens: 1120, inputRatePerM: 0.5,
    },
    'google/nano-banana-pro': {
        outputTokens: { '1k': 1120, '2k': 1120, '4k': 2000 }, outputRatePerM: 120,
        textTokens: 176, textRatePerM: 12,
        refTokens: 560, inputRatePerM: 2,
    },
};
// Two ids, one model: the Gemini card's own description calls itself Nano Banana Pro, and
// its pricing fields are byte-identical (MPI-849 plan, "Three things this list forces").
GEMINI_IMAGE['google/gemini-3-pro-image'] = GEMINI_IMAGE['google/nano-banana-pro'];

/**
 * Seedance bills per token at a rate the feed gets WRONG for an ordinary call. Its
 * `pricing.full` publishes two bands, and the structured `cents_per_input_token` carries
 * the cheaper one — but that band applies only when a `reference_videos` input is supplied.
 * A measured plain text-to-video call billed at the DEARER band, so that is what is quoted
 * by default. Seedance 1.5's constant agrees with the feed; 2.0's deliberately does not.
 */
const SEEDANCE_RATE_PER_M = {
    'ByteDance/Seedance-1.5-Pro': 1.20,
    'ByteDance/Seedance-2.0': 7.70,
};

/**
 * Veo has no `duration` field at all — fixed-length clips — so its structured per-second
 * rate has nothing to multiply until a length is supplied. 8 s reproduces the published
 * headlines: $0.40/s -> $3.20, $0.15/s -> $1.20.
 */
const CLIP_SECONDS = {
    'google/veo-3.1': 8,
    'google/veo-3.1-fast': 8,
};

/** Seedream 5.0 Pro is the one model that bills extra per input image after the first. */
const EXTRA_INPUT_IMAGE_USD = {
    'ByteDance/Seedream-5.0-Pro': 0.0033,
};

const MEGAPIXEL = 1048576;

/** frames = 24 x duration + 1 — measured, and the +1 is worth 1% (01d § 2c). */
export function videoFrames(durationSeconds) {
    return Math.round(24 * durationSeconds) + 1;
}

/** tokens = floor(w x h x frames / 1024) — measured exact at 40,594 for a 480p 4 s clip. */
export function videoTokens(width, height, frames) {
    return Math.floor((width * height * frames) / 1024);
}

function priceImageUnits(modelId, pricing, opts) {
    const cents = pricing.cents_per_image_unit;
    if (!Number.isFinite(cents)) return null;
    let usd = cents / 100;

    // default_width 0 means a CLOSED model: flat per image, resolution irrelevant.
    if (pricing.default_width) {
        const width = opts.width || pricing.default_width;
        const height = opts.height || pricing.default_height;
        usd *= (width * height) / MEGAPIXEL;
        // default_iterations 0 (both kleins) means the price carries no step term at all.
        if (pricing.default_iterations) {
            usd *= (opts.steps || pricing.default_iterations) / pricing.default_iterations;
        }
    }

    const extra = EXTRA_INPUT_IMAGE_USD[modelId];
    if (extra) usd += extra * Math.max(0, (opts.references || 0) - 1);
    return usd;
}

function priceGeminiImage(modelId, opts) {
    const c = GEMINI_IMAGE[modelId];
    // A token-priced image model with no measured token count cannot be priced. Refuse.
    if (!c) return null;
    const bucket = String(opts.resolution || '1k').toLowerCase();
    const outputTokens = c.outputTokens[bucket] ?? c.outputTokens['1k'];
    return outputTokens * c.outputRatePerM / 1e6
        + c.textTokens * c.textRatePerM / 1e6
        + (opts.references || 0) * c.refTokens * c.inputRatePerM / 1e6;
}

function priceTokenVideo(modelId, pricing, opts) {
    const seconds = opts.duration || CLIP_SECONDS[modelId];
    if (!seconds) return null;
    const label = String(opts.resolution || '480p').toLowerCase();
    const px = VIDEO_PIXELS[label];
    const width = opts.width || px?.width;
    const height = opts.height || px?.height;
    if (!width || !height) return null;

    // The measured band wins over the feed's; see SEEDANCE_RATE_PER_M.
    const ratePerM = SEEDANCE_RATE_PER_M[modelId]
        ?? (Number.isFinite(pricing.cents_per_input_token) ? pricing.cents_per_input_token * 1e4 : null);
    if (ratePerM === null) return null;

    return videoTokens(width, height, videoFrames(seconds)) * ratePerM / 1e6;
}

function priceOutputLength(modelId, pricing, opts) {
    const seconds = opts.duration || CLIP_SECONDS[modelId];
    if (!seconds) return null;
    const label = String(opts.resolution || '').toLowerCase();
    const cents = pricing.cents_per_output_sec_by_resolution?.[label] ?? pricing.cents_per_output_sec;
    if (!Number.isFinite(cents)) return null;
    return (cents / 100) * seconds;
}

/**
 * One generation's cost, in USD, from a snapshot entry. Exported so the refusal paths can
 * be tested against pricing shapes the shipped models do not have (`time`, `frame_units`).
 * @returns {number|null} null when this shape cannot be priced before the run.
 */
export function priceFromEntry(modelId, entry, opts = {}) {
    const pricing = entry?.pricing;
    if (!pricing) return null;
    switch (pricing.type) {
        case 'image_units':
            return priceImageUnits(modelId, pricing, opts);
        case 'input_tokens':
            return entry.type === 'text-to-video'
                ? priceTokenVideo(modelId, pricing, opts)
                : priceGeminiImage(modelId, opts);
        case 'output_length':
            return priceOutputLength(modelId, pricing, opts);
        // 'time' is GPU-seconds — not knowable before the run. 'frame_units' ships on no
        // model we offer. Both refuse rather than guess.
        default:
            return null;
    }
}

/**
 * What a generation will cost before it runs.
 *
 * @param {string} modelId  DeepInfra id, e.g. 'google/nano-banana-pro'.
 * @param {{width?:number, height?:number, steps?:number, references?:number, batch?:number,
 *          resolution?:string, duration?:number}} [opts]
 *   `resolution` is a bucket label — '1k'/'2k'/'4k' for images, '480p'/'720p'/'1080p' for
 *   video. `references` counts reference images. `duration` is in seconds.
 * @returns {{usd:number, unit:number, batch:number, display:string, checkedOn:string}|null}
 *   null when the model is unknown or its price is not knowable before the run.
 */
export function estimateCost(modelId, opts = {}) {
    const entry = SNAPSHOT.models[modelId];
    if (!entry) return null;

    const unit = priceFromEntry(modelId, entry, opts);
    if (!Number.isFinite(unit) || unit <= 0) return null;

    const batch = Math.max(1, Math.round(opts.batch || 1));
    const usd = unit * batch;
    return { usd, unit, batch, display: formatPrice(usd), checkedOn: SNAPSHOT.checkedOn };
}

/**
 * Price copy. Always "about", never a four-decimal quote: the Gemini models emit a variable
 * number of text tokens, so an estimate is good to about 2% and a precise-looking figure
 * would be a lie. Never renders "$0.00" either — that reads as free.
 */
export function formatPrice(usd) {
    if (!Number.isFinite(usd) || usd <= 0) return null;
    // Below a cent, two decimals say "$0.00" and a shrug says "under $0.01" — neither tells
    // a user that four images cost less than a postage stamp. One significant figure does,
    // and it cannot mislead: the models whose price carries ~2% of text-token uncertainty
    // are all dearer than 3 cents, so no sub-cent quote is ever one of those. (MPI-853)
    if (usd < 0.01) return `about $${Number(usd.toPrecision(1))}`;
    return `about $${usd.toFixed(2)}`;
}
