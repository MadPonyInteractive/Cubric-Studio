/**
 * Recipe: Wan 3.0 (text-to-video, image-to-video, reference-to-video).
 *
 * STATUS: `draft` — not yet validated on the real model. Stage 2 renders are
 * Fabio's, after Stage 1 passes cleanly.
 *
 * Research in `docs/recipes/research/wan-3.0/` (sources.md + research.md).
 * Sources: Alibaba Cloud official prompt guide (src 1, official-docs),
 * Alibaba Cloud API reference (src 2, official-docs), DeepInfra model page
 * (src 3, official-example), community skills that package the official guide
 * (srcs 4–5). Research date: 2026-10-04.
 *
 * KEY FACTS FROM THE OFFICIAL GUIDE (src 1, outranks everything else):
 *  - Structure: overall description → (r2v) reference citations → action →
 *    dialogue → sound effects and music → style/mood → negative list.
 *  - Multi-shot: `Shot N [Xs-Ys]:` segments, 2-5 seconds each, joined end to
 *    end with named transitions. Timestamps ARE stable and recommended by the
 *    vendor — this is the opposite of Seedance 2.0. Do not port the Seedance
 *    timestamp ban.
 *  - Focal lengths in millimetres are in the official vocabulary ("85mm
 *    telephoto"). Do not port the Seedance degrees-only rule.
 *  - Audio is generated by default. Write what the user asked for; suppress
 *    only when the user asked for silence.
 *  - No negative-prompt API field. Constraints are a trailing list in the
 *    main prompt.
 *
 * REFERENCE TAGS: the app's `@` picker inserts `<Image 1>`, `<Video 1>`,
 * `<Audio 1>` (via `refTagHandle`, `js/data/commandRegistry.js`). The enhancer
 * is told to cite whatever form is in the Attached references line verbatim,
 * as the Seedance 2.0 recipe does. The test harness sends `@image1` / `@video1`
 * style tags in its REF_INPUTS; the recipe handles both.
 *
 * WORD BUDGETS: derived from the official example range (9-57 words for
 * single/multi-shot prompts) and the practical length of multi-shot prompts
 * with dialogue and audio. The 20,000-character API cap is the only hard limit.
 * `prompt_extend` is on by default and expands raw prompts before generation,
 * so the enhancer output can be shorter than what the model ultimately
 * processes. Budgets are to be calibrated in Stage 1.
 *
 * MPI-1018, 2026-10-04.
 */

