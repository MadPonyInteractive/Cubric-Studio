const FORBIDDEN_BASE = [
    { pattern: '\\b(1080[pP]|720[pP]|480[pP]|4K|8K)\\b', why: 'a resolution: the app sets it' },
    { pattern: '\\b(16:9|9:16|4:3|3:4|21:9|1:1)\\b', why: 'an aspect ratio: the app sets it' },
    // Measured on the first t2v sweep (bare, run 3): the enhancer reproduced the recipe's
    // structural section names as output labels ("Camera:", "Sound_effects:", "Style and Mood:").
    // The output format rule says "no section labels" but the judge waved them through.
    {
        pattern: '(^|\\n)\\s*(Camera|Sound[_ ]?[Ee]ffects?|Sound|Music|Style and Mood|Style|Mood|Dialogue and Voice|Negative List|Overall Description|Overall|Action|Transition|Citation)\\s*:',
        why: 'a section label: the prompt is plain prose with no headings',
    },
];

