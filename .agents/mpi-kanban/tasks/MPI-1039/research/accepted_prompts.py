# Flow build phase 2 input: the exact prompt (from the card's sidecar) behind every grid cell flow-spec.md accepts,
# seed 111, anime + photo, written to accepted_prompts.md - the words multiAngle.js generalises.
# Usage: python accepted_prompts.py
import glob
import json
import os
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out')
META = os.path.expanduser('~/Documents/Cubric Studio/Projects/FLUX3 Flow Bench/Media/.meta')
CELLS = [  # (stop, round, key with {n} = anime|photo); round 23 / 25 name the anime source 'street 222'
    ('front lo', 30, '{n} 111 front lo reveal'), ('front hi', 23, 'street 222 111 front hi'),
    ('tq fl', 27, '{n} 111 tq fl side'), ('tq fr', 31, '{n} 111 tq fr'),
    ('pr l', 35, '{n} 111 pr l'), ('pr r', 35, '{n} 111 pr r'),
    ('tqb l', 31, '{n} 111 tqb l'), ('tqb r', 39, '{n} 111 tqb r'), ('back', 24, '{n} 111 back eye'),
    ('tq fl lo', 30, '{n} 111 tq fl lo'), ('tq fr lo', 31, '{n} 111 tq fr lo'), ('pr l lo', 35, '{n} 111 pr l lo'),
    ('pr r lo', 35, '{n} 111 pr r lo'), ('tqb l lo', 31, '{n} 111 tqb l lo'), ('tqb r lo', 40, '{n} 111 tqb r lo'),
    ('back lo', 31, '{n} 111 back lo'),
    ('tq fl hi', 34, '{n} 111 tq fl hi framed'), ('tq fr hi', 35, '{n} 111 tq fr hi'),
    ('pr l hi', 35, '{n} 111 pr l hi'), ('pr r hi', 35, '{n} 111 pr r hi'), ('tqb l hi', 35, '{n} 111 tqb l hi'),
    ('tqb r hi', 40, '{n} 111 tqb r hi'), ('back hi', 35, '{n} 111 back hi'),
    ('zoom hs', 43, '{n} 111 front hs'), ('zoom face', 44, '{n} 111 front face chain'),
    ('zoom eye', 43, '{n} 111 front eye'), ('zoom waist', 46, '{n} 111 hs waist'),
    ('zoom full', 46, '{n} 111 hs full'), ('zoom far', 49, '{n} 111 far chain'),
    ('zoom rear waist', 49, '{n} 111 rear waist'), ('zoom rear hs', 49, '{n} 111 rear hs'),
] + [(f'zoom {v} {r}', 50, f'{{n}} 111 {v} {r}') for v in ('tq fl', 'tq fr', 'pr l', 'pr r', 'tqb l', 'back')
     for r in ('hs', 'far') if (v, r) != ('tqb l', 'hs')] + [  # round 50; tqb l hs lands at the waist
    (f'zoom {v} {h} {r}', 51, f'{{n}} 111 {v} {h} {r}')
    for v in ('front', 'tq fl', 'tq fr', 'pr l', 'pr r', 'tqb l', 'tqb r', 'back') for h in ('lo', 'hi')
    for r in ('hs', 'far') if r == 'far' or (h == 'hi' and v != 'front')]  # round 51: hs only from above, turned

by_file = {}
for p in glob.glob(os.path.join(META, '*.json')):
    try:
        d = json.load(open(p, encoding='utf-8'))
    except (ValueError, OSError):
        continue
    if isinstance(d, dict) and d.get('filePath'):
        by_file[os.path.basename(urllib.parse.unquote(d['filePath'].split('path=')[1].split('&')[0]))] = d

lines = ['# Accepted prompts per grid cell (seed 111)', '', 'Generated by accepted_prompts.py from the bench cards\' '
         'sidecars. Do not edit by hand.', '']
rounds = {}
for stop, rnd, key in CELLS:
    if rnd not in rounds:
        p = os.path.join(OUT, f'mq_blender{rnd}.json')
        rounds[rnd] = json.load(open(p)) if os.path.exists(p) else {}
    for n in ('anime', 'photo'):
        k = key.format(n=n)
        if '{n}' not in key and n == 'photo':
            continue  # an anime-only cell (front hi: no photo cell in the round-23 grid)
        url = rounds[rnd].get(k)
        if not url:
            continue
        side = by_file.get(os.path.basename(urllib.parse.unquote(url.split('path=')[1].split('&')[0])))
        if not side:
            lines += [f'## {stop} - {n} (r{rnd} `{k}`)', '', 'NO SIDECAR', '']
            continue
        lines += [f'## {stop} - {n} (r{rnd} `{k}`, {side.get("modelId")})', '', '```text', side.get('prompt', ''),
                  '```', '']
open(os.path.join(HERE, 'accepted_prompts.md'), 'w', encoding='utf-8').write('\n'.join(lines))
# The same prompts as the test fixture multiAngle.js is pinned against (tests/multi-angle-prompts.test.cjs).
fixture = {}
for i, x in enumerate(lines):
    if x.startswith('## ') and lines[i + 2] == '```text':
        stop, style = x[3:].split(' (')[0].rsplit(' - ', 1)
        fixture[f'{stop} | {style}'] = lines[i + 3]
json.dump(fixture, open(os.path.join(HERE, *[os.pardir] * 5, 'tests', 'fixtures', 'multi-angle-bench-prompts.json'),
                        'w', encoding='utf-8'), indent=1, ensure_ascii=False)
print(sum(1 for x in lines if x.startswith('## ')), 'cells')
