"""MPI-1148: apply bench variant H to the shipped Klein graphs (raw + runtime), in place.

Pass 1 (the portrait) no longer takes the body picture as a reference - the clothes caption carries the
body's clothes - and its prompt ends on a framing sentence, after the user's words. Removes #53 #54 (the
with-body portrait prompt + its switch) and #71 #72 (the body reference + its switch).
"""
import json, os

ROOT = os.path.join(os.path.dirname(__file__), '../../../../..')
RAW = os.path.join(ROOT, 'comfy_workflows/raw/flow_character_sheet_from_images_klein.json')
API = os.path.join(ROOT, 'comfy_workflows/flow_character_sheet_from_images_klein.json')
TAIL = ' The picture is a close-up: only the head, neck and the top of the shoulders are in frame, nothing below the chest.'
GONE = (53, 54, 71, 72)


def fix_api():
    g = json.load(open(API, encoding='utf-8'))
    assert g['52']['_meta']['title'] == 'Portrait_Prompt_No_Body' and g['72']['_meta']['title'].startswith('Pass1_Conditioning')
    for k in GONE:
        del g[str(k)]
    g['58']['inputs']['string_a'] = ['52', 0]
    g['73']['inputs']['positive'] = ['70', 0]
    g['52']['inputs']['value'] += TAIL
    for k, n in g.items():  # nothing may still point at a removed node
        for v in n['inputs'].values():
            assert not (isinstance(v, list) and v and v[0] in map(str, GONE)), (k, v)
    return g


def fix_raw():
    g = json.load(open(RAW, encoding='utf-8'))
    nodes = {n['id']: n for n in g['nodes']}
    links = {l[0]: l for l in g['links']}

    def drop(lid):
        _, src, slot, dst, dslot, _t = links.pop(lid)
        if src in nodes:
            out = nodes[src]['outputs'][slot]
            out['links'] = [x for x in out['links'] if x != lid]
        if dst in nodes:
            for i in nodes[dst]['inputs']:
                if i.get('link') == lid:
                    i['link'] = None

    def retarget(lid, dst, name):
        slot = next(j for j, i in enumerate(nodes[dst]['inputs']) if i['name'] == name)
        old = nodes[dst]['inputs'][slot].get('link')
        if old is not None:
            drop(old)
        links[lid][3], links[lid][4] = dst, slot
        nodes[dst]['inputs'][slot]['link'] = lid

    retarget(60, 58, 'string_a')   # 52 -> 58, was 52 -> 54.false
    retarget(86, 73, 'positive')   # 70 -> 73, was 70 -> 72.false
    for lid in [l[0] for l in list(links.values()) if l[1] in GONE or l[3] in GONE]:
        drop(lid)
    for k in GONE:
        del nodes[k]
    v = nodes[52]['widgets_values']
    v[0] += TAIL
    note = nodes[1]['widgets_values']
    note[0] = note[0].replace('(generated by build_bench_v2.py --flow).',
                              '(generated by build_bench_v2.py --flow, then edited in place: the LoRA rack, MPI-1036; '
                              'pass 1 without the body picture, MPI-1148 research/apply_fix.py).', 1)
    assert 'MPI-1148' in note[0]
    g['nodes'] = [n for n in g['nodes'] if n['id'] not in GONE]
    g['links'] = [l for l in g['links'] if l[0] in links]
    for n in g['nodes']:  # every link a node names exists, and points back at it
        for i in n.get('inputs', []):
            assert i.get('link') is None or links[i['link']][3] == n['id'], (n['id'], i)
        for o in n.get('outputs', []):
            for lid in o.get('links') or []:
                assert links[lid][1] == n['id'], (n['id'], lid)
    return g


api, raw = fix_api(), fix_raw()
for path, g in ((API, api), (RAW, raw)):
    open(path, 'w', encoding='utf-8', newline='\n').write(json.dumps(g, indent=2, ensure_ascii=False) + '\n')
print('API nodes', len(api), '| raw nodes', len(raw['nodes']), 'links', len(raw['links']))
