#!/usr/bin/env node

// MPI-850 — regenerate dev_configs/deepinfra-prices.json from DeepInfra's own catalogue.
//
// DeepInfra publishes a structured price on `GET https://api.deepinfra.com/models/list`,
// and that endpoint needs NO API KEY. Counted 2026-09-20: 62 of the 69 live image and
// video models carry a fully machine-readable price. So the app never has to hold a
// hand-kept price table — it holds a SNAPSHOT of theirs, and every price change arrives
// as a reviewable diff instead of a silent drift under a user's estimate.
//
// The seven that price themselves badly (the Gemini family's per-resolution token counts,
// Seedance's, and Seedance 2.0's two bands) are NOT repaired here. Their measured
// constants live next to the arithmetic in js/data/modelConstants/deepinfraPricing.js,
// because they came from real billed calls, not from this feed.
//
// Usage:
//   node scripts/sync-deepinfra-prices.mjs            rewrite the snapshot
//   node scripts/sync-deepinfra-prices.mjs --check    exit 1 if the snapshot is stale
//
// Exit 1 when a model we ship has vanished from the catalogue or gone deprecated: a
// snapshot that quietly drops a model would leave its tile priceless, which reads as free.

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const LIST_URL = 'https://api.deepinfra.com/models/list';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'dev_configs', 'deepinfra-prices.json');

// The models MPI-849 ships, Fabio's list of 2026-09-20 (.agents/mpi-kanban/tasks/MPI-849/plan.md),
// plus FLUX-1-schnell — the cheapest real dispatch on the platform at $0.0005, which is what
// MPI-851 smoke-tests the executor with and what pins the open-image formula in the tests.
// MPI-851 puts a `provider` on the ModelDef; once it lands this list can be derived from
// models.js instead of repeated here.
const SHIPPED = [
    'ByteDance/Seedream-4',
    'ByteDance/Seedream-4.5',
    'ByteDance/Seedream-5.0-Pro',
    'black-forest-labs/FLUX-2-dev',
    'black-forest-labs/FLUX-2-pro',
    'black-forest-labs/FLUX-2-max',
    'black-forest-labs/FLUX-1-schnell',
    'google/nano-banana-2-lite',
    'google/nano-banana-2',
    'google/nano-banana-pro',
    'google/gemini-3-pro-image',
    'ByteDance/Seedance-1.5-Pro',
    'ByteDance/Seedance-2.0',
    'Wan-AI/Wan3.0-Video',
    'google/veo-3.1-fast',
    'google/veo-3.1',
];

/** "1080P" / "$0.20" rows → { '1080p': 20 } in CENTS per second, the unit the feed uses. */
function tiersFromTable(table) {
    const rows = table?.rows;
    if (!Array.isArray(rows)) return null;
    const out = {};
    for (const [resolution, price] of rows) {
        const cents = Math.round(parseFloat(String(price).replace(/[^0-9.]/g, '')) * 100);
        if (!Number.isFinite(cents)) return null;
        out[String(resolution).toLowerCase()] = cents;
    }
    return Object.keys(out).length ? out : null;
}

/** Copy only the fields the price module reads — the diff stays about prices. */
function entryFor(model) {
    const p = model.pricing || {};
    const pricing = { type: p.type };
    for (const key of ['cents_per_image_unit', 'default_width', 'default_height', 'default_iterations',
        'cents_per_input_token', 'cents_per_output_sec']) {
        if (p[key] !== undefined && p[key] !== null) pricing[key] = p[key];
    }
    const tiers = tiersFromTable(p.table);
    if (tiers) pricing.cents_per_output_sec_by_resolution = tiers;
    // The prose is the only published source for the tiered models (Seedream 5's 1.5K
    // threshold, Nano Banana Pro's 4K bucket). Carried so a reviewer can see WHY a
    // constant next door says what it says.
    if (p.full) pricing.full = p.full;
    return { type: model.type, pricing };
}

async function build() {
    const res = await fetch(LIST_URL);
    if (!res.ok) throw new Error(`${LIST_URL} → HTTP ${res.status}`);
    const all = await res.json();

    const models = {};
    const missing = [];
    for (const id of SHIPPED) {
        const model = all.find((m) => m.model_name === id);
        if (!model) { missing.push(`${id} — not in the catalogue any more`); continue; }
        if (model.deprecated) { missing.push(`${id} — deprecated ${model.deprecated}`); continue; }
        models[id] = entryFor(model);
    }
    if (missing.length) {
        console.error('DeepInfra no longer offers:\n  ' + missing.join('\n  '));
        console.error('\nDrop the model from SHIPPED and from its ModelDef, or the app prices a model nobody can run.');
        process.exit(1);
    }

    return {
        schema: 'cubric/deepinfra-prices/v1',
        checkedOn: new Date().toISOString().slice(0, 10),
        source: LIST_URL,
        note: 'GENERATED by scripts/sync-deepinfra-prices.mjs — never hand-edit. Measured constants the feed cannot express live in js/data/modelConstants/deepinfraPricing.js.',
        models,
    };
}

const snapshot = await build();
const json = JSON.stringify(snapshot, null, 4) + '\n';

if (process.argv.includes('--check')) {
    const onDisk = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    const strip = (s) => s.replace(/"checkedOn": "[^"]*",\n/, '');
    if (strip(onDisk) === strip(json)) {
        console.log(`Prices unchanged since ${snapshot.checkedOn}.`);
        process.exit(0);
    }
    console.error('dev_configs/deepinfra-prices.json is STALE — run: node scripts/sync-deepinfra-prices.mjs');
    process.exit(1);
}

fs.writeFileSync(OUT, json);
console.log(`Wrote ${Object.keys(snapshot.models).length} models to ${path.relative(process.cwd(), OUT)} (checked ${snapshot.checkedOn}).`);
